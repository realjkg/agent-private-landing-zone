import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { OPERATIONS } from "./registry.js";
import { FAMILIES, FAMILY_TITLES } from "./types.js";

export const DOC_PATH = "docs/operator-console.md";
const START = "<!-- operations:start (generated by npm run docs:ops; do not edit) -->";
const END = "<!-- operations:end -->";

const cell = (text: string): string => text.replaceAll("|", "\\|");

/** The catalog as a Markdown table, in family order. */
export function renderOperationsTable(): string {
  const rows = FAMILIES.flatMap((family) => OPERATIONS.filter((spec) => spec.family === family).map((spec) =>
    "| " + [FAMILY_TITLES[family], spec.title, "`" + cell(spec.cli) + "`", spec.safety,
      spec.safety === "HANDOFF" ? "Guided handoff" : "Run", cell(spec.evidenceBasis)].join(" | ") + " |"));
  return ["| Family | Operation | CLI | Safety | Console | Evidence basis |",
    "| --- | --- | --- | --- | --- | --- |", ...rows].join("\n");
}

/** The document with its generated block replaced. */
export function renderDoc(current: string): string {
  const from = current.indexOf(START);
  const to = current.indexOf(END);
  if (from < 0 || to < from) throw new Error("OPERATIONS_DOC_MARKERS_MISSING");
  return current.slice(0, from + START.length) + "\n" + renderOperationsTable() + "\n" + current.slice(to);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const path = resolve(fileURLToPath(new URL("../..", import.meta.url)), DOC_PATH);
  writeFileSync(path, renderDoc(readFileSync(path, "utf8")));
  console.log("Updated " + DOC_PATH);
}
